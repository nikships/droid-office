import assert from 'node:assert/strict';
import test from 'node:test';
import { readFileSync } from 'node:fs';
import * as THREE from 'three';
import { installLoftCouch } from '../src/client/world/loft-couch.js';
import { SEATING_BY_ID } from '../src/shared/layout.js';
import { surfaceFinish } from '../src/client/world/surface.js';

test('loft couch keeps both seat anchors, west-facing mount and picking while sharing geometry', () => {
  const seat = SEATING_BY_ID.get('loft-couch')!;
  const office = new THREE.Group();
  const couch = new THREE.Group();
  couch.name = 'loft-couch';
  couch.position.set(seat.x, seat.y, seat.z);
  const interact = { kind: 'seat', seatId: seat.id, x: seat.x, y: seat.y, z: seat.z, radius: 1.8 };
  couch.userData.interact = interact;
  couch.add(new THREE.Object3D());
  const neighbor = new THREE.Group();
  office.add(couch, neighbor);
  const source = new THREE.Group();
  const part = new THREE.Group();
  part.name = 'LoftCouch';
  const fabric = new THREE.MeshStandardMaterial({ name: 'LoftFabric', color: '#87898c' });
  const metal = new THREE.MeshStandardMaterial({ name: 'LoftSteel', color: '#62686e', metalness: 0.75 });
  const orange = new THREE.MeshStandardMaterial({ name: 'LoftOrange', color: '#ee6018' });
  const original = [fabric, metal, orange, fabric];
  const geometry = new THREE.BoxGeometry(1.1, 0.98, 2.5);
  part.add(new THREE.Mesh(geometry, original), new THREE.Mesh(geometry, fabric));
  source.add(part);
  assert.equal(installLoftCouch(source, office), true);
  assert.deepEqual(couch.position.toArray(), [seat.x, seat.y, seat.z]);
  assert.ok(couch.quaternion.equals(new THREE.Quaternion()));
  assert.equal(couch.userData.interact, interact);
  assert.equal(office.children[1], neighbor);
  assert.deepEqual(seat.places, [-0.5, 0.5]);
  assert.equal(seat.hips, 0.5);
  assert.equal(seat.depth, -0.05);
  const direction = new THREE.Vector3(-1, 0, 0).applyQuaternion(couch.quaternion);
  assert.ok(direction.distanceTo(new THREE.Vector3(Math.sin(seat.rotY), 0, Math.cos(seat.rotY))) < 1e-12);
  const model = couch.children[0];
  const mesh = model.children[0] as THREE.Mesh;
  const materials = mesh.material as THREE.MeshToonMaterial[];
  assert.equal(mesh.geometry, geometry);
  assert.ok(materials.every((m) => m.isMeshToonMaterial));
  assert.deepEqual(materials.map(surfaceFinish), [null, [0.55, 0.3], null, null]);
  assert.equal(materials[0], materials[3]);
  assert.equal((model.children[1] as THREE.Mesh).material, materials[0]);
  assert.ok(materials[2].color.equals(orange.color));
  assert.equal(materials[2].emissive.getHex(), 0);
  assert.equal((part.children[0] as THREE.Mesh).material, original);
  assert.equal(part.parent, source);
});

test('missing loft couch assets or mount retain the procedural fallback', () => {
  const office = new THREE.Group();
  const couch = new THREE.Group();
  couch.name = 'loft-couch';
  const fallback = new THREE.Object3D();
  couch.add(fallback);
  office.add(couch);
  assert.equal(installLoftCouch(new THREE.Group(), office), false);
  assert.equal(couch.children[0], fallback);
  const source = new THREE.Group();
  source.name = 'LoftCouch';
  assert.equal(installLoftCouch(source, new THREE.Group()), false);
});

test('actual loft couch GLB has its back on +x and retains the original compact envelope', () => {
  const manifest = JSON.parse(readFileSync(new URL('../src/client/public/props/manifest.json', import.meta.url), 'utf8'));
  const couch = manifest['loft-couch'];
  assert.equal(couch.width, 1.1);
  assert.equal(couch.height, 0.98);
  assert.ok(Math.abs(couch.depth - 2.5) < 0.01);
  assert.ok(couch.triangles <= 8000);
  assert.equal(couch.materials, 6);
  const glb = readFileSync(new URL('../src/client/public/props/loft-couch.glb', import.meta.url));
  assert.equal(glb.byteLength, couch.bytes);
  const json = JSON.parse(glb.subarray(20, 20 + glb.readUInt32LE(12)).toString('utf8'));
  assert.ok(json.nodes.some((n: { name: string }) => n.name === 'LoftCouch'));
  type Primitive = { material: number; attributes: { POSITION: number } };
  const primitives: Primitive[] = json.meshes.flatMap((m: { primitives: Primitive[] }) => m.primitives);
  const back = primitives.find((p) => json.materials[p.material].name === 'LoftBackShell');
  assert.ok(back);
  const bounds = json.accessors[back.attributes.POSITION];
  assert.ok(bounds.min[0] > 0.31 && bounds.max[0] < 0.601, 'back is +x, so the front faces the original west-facing seats');
});
