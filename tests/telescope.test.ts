import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import * as THREE from 'three';
import { installTelescope } from '../src/client/world/telescope.js';
import { surfaceFinish } from '../src/client/world/surface.js';
import { LOFT } from '../src/shared/layout.js';

function destination() {
  const office = new THREE.Group();
  const scope = new THREE.Group();
  scope.position.set(LOFT.minX + 0.9, LOFT.y, LOFT.minZ + 0.9);
  const stand = new THREE.Group();
  stand.name = 'telescope-stand';
  stand.add(new THREE.Object3D());
  const tube = new THREE.Group();
  tube.name = 'telescope-tube';
  tube.position.y = 1.08;
  tube.add(new THREE.Object3D());
  scope.add(stand, tube);
  office.add(scope);
  tube.lookAt(-6, 0.8, 0);
  return { office, scope, stand, tube };
}

test('telescope swaps both parts while retaining the mount, optical axis and exact aim', () => {
  const { office, scope, stand, tube } = destination();
  const aim = tube.quaternion.clone();
  const paint = new THREE.MeshStandardMaterial({ name: 'ScopePaint', color: '#666f78' });
  const steel = new THREE.MeshStandardMaterial({ name: 'ScopeSteel', color: '#b0bac3', metalness: 0.85 });
  const rubber = new THREE.MeshStandardMaterial({ name: 'ScopeRubber' });
  const orange = new THREE.MeshStandardMaterial({ name: 'ScopeSignal', color: '#ee6018' });
  const glass = new THREE.MeshStandardMaterial({ name: 'ScopeLens', color: '#294e63' });
  const source = new THREE.Group();
  const base = new THREE.Mesh(new THREE.BoxGeometry(), [paint, steel, rubber, orange]);
  base.name = 'TelescopeStand';
  const optics = new THREE.Group();
  optics.name = 'TelescopeOptics';
  const body = new THREE.Mesh(new THREE.BoxGeometry(0.12, 0.12, 0.86).translate(0, 1.08, 0.1), paint);
  const lens = new THREE.Mesh(new THREE.SphereGeometry(0.09), glass);
  lens.position.set(0, 1.08, 0.575);
  optics.add(body, lens);
  source.add(base, optics);
  assert.equal(installTelescope(source, office), true);
  assert.deepEqual(scope.position.toArray(), [LOFT.minX + 0.9, LOFT.y, LOFT.minZ + 0.9]);
  assert.deepEqual(tube.position.toArray(), [0, 1.08, 0]);
  assert.ok(tube.quaternion.equals(aim));
  const loaded = stand.children[0] as THREE.Mesh;
  assert.equal(loaded.geometry, base.geometry);
  const materials = loaded.material as THREE.MeshToonMaterial[];
  assert.ok(materials.every((m) => m.isMeshToonMaterial));
  assert.deepEqual(surfaceFinish(materials[0]), [0.04, 0.72]);
  assert.deepEqual(surfaceFinish(materials[1]), [0.55, 0.3]);
  assert.equal(surfaceFinish(materials[2]), null);
  assert.equal(surfaceFinish(materials[3]), null);
  const optical = tube.children[0];
  assert.equal((optical.children[0] as THREE.Mesh).geometry, body.geometry);
  assert.equal((optical.children[0] as THREE.Mesh).material, materials[0]);
  const lensMaterial = (optical.children[1] as THREE.Mesh).material as THREE.MeshBasicMaterial;
  assert.ok(lensMaterial.isMeshBasicMaterial);
  assert.equal(lensMaterial.transparent, true);
  assert.equal(lensMaterial.opacity, 0.8);
  assert.equal(lens.material, glass);
  assert.equal(base.material[0], paint);
  office.updateMatrixWorld(true);
  const direction = tube.getWorldDirection(new THREE.Vector3());
  const origin = tube.getWorldPosition(new THREE.Vector3());
  assert.ok(direction.distanceTo(new THREE.Vector3(-6, 0.8, 0).sub(origin).normalize()) < 1e-12);
  const actual = new THREE.Vector3(0, 1.08, 0.55).applyMatrix4(optical.matrixWorld);
  const expected = origin.addScaledVector(direction, 0.55);
  assert.ok(actual.distanceTo(expected) < 1e-12, 'authored 1.08 m offset must not be applied twice');
  assert.deepEqual(optics.position.toArray(), [0, 0, 0]);
});

test('incomplete telescope nodes keep both fallbacks and single materials work', () => {
  const { office, stand, tube } = destination();
  const original = [stand.children[0], tube.children[0]];
  const source = new THREE.Group();
  const base = new THREE.Mesh(new THREE.BoxGeometry(), new THREE.MeshStandardMaterial({ name: 'ScopeRubber' }));
  base.name = 'TelescopeStand';
  const optics = base.clone();
  optics.name = 'TelescopeOptics';
  source.add(base);
  assert.equal(installTelescope(source, office), false);
  source.remove(base);
  source.add(optics);
  assert.equal(installTelescope(source, office), false);
  assert.deepEqual([stand.children[0], tube.children[0]], original);
  source.add(base);
  assert.equal(installTelescope(source, new THREE.Group()), false);
  const missingTube = new THREE.Group();
  missingTube.add(new THREE.Group());
  missingTube.children[0].name = 'telescope-stand';
  assert.equal(installTelescope(source, missingTube), false);
  assert.equal(installTelescope(source, office), true);
  assert.ok(((stand.children[0] as THREE.Mesh).material as THREE.MeshToonMaterial).isMeshToonMaterial);
});

test('telescope GLB retains both nodes, rest-pose lens height and triangle budget', () => {
  const manifest = JSON.parse(readFileSync(new URL('../src/client/public/props/manifest.json', import.meta.url), 'utf8'));
  const telescope = manifest.telescope;
  assert.ok(telescope.triangles <= 8000);
  assert.equal(telescope.materials, 5);
  assert.ok(telescope.width > 0.65 && telescope.width < 0.8);
  assert.equal(telescope.height, 1.23);
  const glb = readFileSync(new URL('../src/client/public/props/telescope.glb', import.meta.url));
  assert.equal(glb.byteLength, telescope.bytes);
  const json = JSON.parse(glb.subarray(20, 20 + glb.readUInt32LE(12)).toString('utf8'));
  for (const name of ['TelescopeStand', 'TelescopeOptics']) assert.ok(json.nodes.some((n: { name: string }) => n.name === name));
  const lenses = json.meshes.flatMap((m: { primitives: { material: number; attributes: { POSITION: number } }[] }) => m.primitives).filter((p: { material: number }) => json.materials[p.material].name === 'ScopeLens');
  assert.ok(lenses.length > 0);
  for (const p of lenses) assert.ok(json.accessors[p.attributes.POSITION].min[1] > 0.9);
});
