        static bool Includes(int[] ranges, int scalar)
        {
            var low = 0; var high = ranges.Length / 2 - 1;
            while (low <= high)
            {
                var at = (low + high) / 2;
                if (scalar < ranges[at * 2]) high = at - 1;
                else if (scalar > ranges[at * 2 + 1]) low = at + 1;
                else return true;
            }
            return false;
        }
        public static int Width(int scalar) => Includes(Zero, scalar) ? 0 : Includes(Wide, scalar) ? 2 : 1;
        public static int TextWidth(string text)
        {
            var width = 0;
            for (var i = 0; i < text.Length; i++)
            {
                var scalar = char.ConvertToUtf32(text, i);
                if (scalar > ushort.MaxValue) i++;
                width += Width(scalar);
            }
            return width;
        }
